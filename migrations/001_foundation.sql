CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(254) NOT NULL UNIQUE CHECK (email = lower(email)),
    password_hash text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE organizations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(120) NOT NULL CHECK (length(trim(name)) > 0),
    created_by bigint NOT NULL REFERENCES users(id),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE organization_memberships (
    organization_id bigint NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
    user_id bigint NOT NULL REFERENCES users(id),
    PRIMARY KEY (organization_id, user_id)
);

CREATE TABLE projects (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id bigint NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
    name varchar(120) NOT NULL CHECK (length(trim(name)) > 0),
    description text NOT NULL DEFAULT '',
    created_by bigint NOT NULL REFERENCES users(id),
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (organization_id, id)
);

CREATE TABLE project_memberships (
    organization_id bigint NOT NULL,
    project_id bigint NOT NULL,
    user_id bigint NOT NULL,
    role text NOT NULL CHECK (role IN ('owner', 'editor', 'viewer')),
    PRIMARY KEY (project_id, user_id),
    FOREIGN KEY (organization_id, project_id)
        REFERENCES projects(organization_id, id) ON DELETE CASCADE,
    FOREIGN KEY (organization_id, user_id)
        REFERENCES organization_memberships(organization_id, user_id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX one_owner_per_project ON project_memberships(project_id) WHERE role = 'owner';
CREATE INDEX memberships_by_user ON project_memberships(user_id, organization_id, project_id);

CREATE TABLE tasks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id bigint NOT NULL,
    project_id bigint NOT NULL,
    title varchar(200) NOT NULL CHECK (length(trim(title)) > 0),
    description text NOT NULL DEFAULT '',
    status text NOT NULL DEFAULT 'todo' CHECK (status IN ('todo', 'in_progress', 'done')),
    created_by bigint NOT NULL REFERENCES users(id),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (organization_id, project_id)
        REFERENCES projects(organization_id, id) ON DELETE CASCADE
);
CREATE INDEX tasks_by_project ON tasks(organization_id, project_id, id);

CREATE TABLE auth_sessions (
    token_digest char(64) PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz NOT NULL,
    revoked_at timestamptz,
    CHECK (expires_at > created_at)
);
CREATE INDEX sessions_by_user ON auth_sessions(user_id);

-- A unique index alone permits zero owners. Deferred checks allow project+owner
-- insertion in one transaction while rejecting ownerless committed projects.
CREATE FUNCTION check_project_owner() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    old_id bigint;
    new_id bigint;
    candidate bigint;
BEGIN
    IF TG_TABLE_NAME = 'projects' THEN
        old_id := (to_jsonb(OLD)->>'id')::bigint;
        new_id := (to_jsonb(NEW)->>'id')::bigint;
    ELSE
        old_id := (to_jsonb(OLD)->>'project_id')::bigint;
        new_id := (to_jsonb(NEW)->>'project_id')::bigint;
    END IF;
    FOR candidate IN SELECT DISTINCT x FROM unnest(ARRAY[old_id, new_id]) AS x WHERE x IS NOT NULL
    LOOP
        IF EXISTS (SELECT 1 FROM projects WHERE id = candidate)
           AND (SELECT count(*) FROM project_memberships
                WHERE project_id = candidate AND role = 'owner') <> 1 THEN
            RAISE EXCEPTION 'Project must retain exactly one owner' USING ERRCODE = '23514';
        END IF;
    END LOOP;
    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER project_requires_owner
AFTER INSERT OR UPDATE ON projects DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION check_project_owner();

CREATE CONSTRAINT TRIGGER membership_preserves_owner
AFTER INSERT OR UPDATE OR DELETE ON project_memberships DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION check_project_owner();

-- Ownership transfer is deliberately outside this project's scope.
CREATE FUNCTION prevent_owner_transfer() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.role = 'owner' AND
       (NEW.role <> OLD.role OR NEW.user_id <> OLD.user_id OR
        NEW.project_id <> OLD.project_id OR NEW.organization_id <> OLD.organization_id) THEN
        RAISE EXCEPTION 'Ownership transfer is out of scope' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER immutable_owner BEFORE UPDATE ON project_memberships
FOR EACH ROW EXECUTE FUNCTION prevent_owner_transfer();

CREATE FUNCTION prevent_owner_removal() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.role = 'owner' AND EXISTS (SELECT 1 FROM projects WHERE id = OLD.project_id) THEN
        RAISE EXCEPTION 'Owner cannot be removed or replaced' USING ERRCODE = '23514';
    END IF;
    RETURN OLD;
END;
$$;
CREATE TRIGGER immutable_owner_delete BEFORE DELETE ON project_memberships
FOR EACH ROW EXECUTE FUNCTION prevent_owner_removal();
